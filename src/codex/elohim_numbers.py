def records() -> list[dict]:
    """Return detached numerical attestations."""
    return [dict(zip(FIELDS, row, strict=True)) for row in ROWS]


def lookup(record_id: str) -> dict:
    """Find one specific claim."""
    for item in records():
        if item["id"] == record_id:
            return item
    raise ValueError(f"Unknown numerical record: {record_id}")


def match(value: int) -> list[dict]:
    """Find exact numerical matches without inferring shared meaning."""
    return [item for item in records() if item["value"] == value]


def contrast(left: str, right: str) -> dict:
    """Separate numeric equality from equivalence of units or referents."""
    a, b = lookup(left), lookup(right)
    known = a["value"] is not None and b["value"] is not None
    same_unit = a["unit"] == b["unit"]
    return {
        "left": a,
        "right": b,
        "numeric_equal": a["value"] == b["value"] if known else None,
        "same_unit": same_unit,
        "arithmetic_difference": b["value"] - a["value"] if known and same_unit else None,
        "equivalent_referents_established": False,
        "genesis_addressee_count": None,
        "boundary": "Arithmetic comparison does not establish historical or symbolic identity.",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("list")
    search = sub.add_parser("match")
    search.add_argument("value", type=int)
    pair = sub.add_parser("contrast")
    pair.add_argument("left")
    pair.add_argument("right")
    args = parser.parse_args()
    try:
        if args.command == "list":
            result = records()
        elif args.command == "match":
            result = match(args.value)
        else:
            result = contrast(args.left, args.right)
    except ValueError as exc:
        parser.error(str(exc))
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
